package pool

// Pools of 6 and 7 follow FIE Organisation Rules (Dec 2025) o.69; 4 to 10 follow USA Fencing
// Rules for Competition o.69; there is no official order for 2 or 3.
func poolBoutOrder(size int) [][2]int {
	switch size {
	case 2:
		return [][2]int{{1, 2}}
	case 3:
		return [][2]int{{1, 2}, {2, 3}, {3, 1}}
	case 4:
		return [][2]int{{1, 4}, {2, 3}, {1, 3}, {2, 4}, {3, 4}, {1, 2}}
	case 5:
		return [][2]int{{1, 2}, {3, 4}, {5, 1}, {2, 3}, {5, 4}, {1, 3}, {2, 5}, {4, 1}, {3, 5}, {4, 2}}
	case 6:
		return [][2]int{
			{1, 2}, {4, 3}, {6, 5}, {3, 1}, {2, 6}, {5, 4}, {1, 6}, {3, 5},
			{4, 2}, {5, 1}, {6, 4}, {2, 3}, {1, 4}, {5, 2}, {3, 6},
		}
	case 7:
		return [][2]int{
			{1, 4}, {2, 5}, {3, 6}, {7, 1}, {5, 4}, {2, 3}, {6, 7}, {5, 1}, {4, 3}, {6, 2}, {5, 7},
			{3, 1}, {4, 6}, {7, 2}, {3, 5}, {1, 6}, {2, 4}, {7, 3}, {6, 5}, {1, 2}, {4, 7},
		}
	case 8:
		return [][2]int{
			{2, 3}, {1, 5}, {7, 4}, {6, 8}, {1, 2}, {3, 4}, {5, 6}, {8, 7}, {4, 1}, {5, 2},
			{8, 3}, {6, 7}, {4, 2}, {8, 1}, {7, 5}, {3, 6}, {2, 8}, {5, 4}, {6, 1}, {3, 7},
			{4, 8}, {2, 6}, {3, 5}, {1, 7}, {4, 6}, {8, 5}, {7, 2}, {1, 3},
		}
	case 9:
		return [][2]int{
			{1, 9}, {2, 8}, {3, 7}, {4, 6}, {1, 5}, {2, 9}, {8, 3}, {7, 4}, {6, 5}, {1, 2},
			{9, 3}, {8, 4}, {7, 5}, {6, 1}, {3, 2}, {9, 4}, {5, 8}, {7, 6}, {3, 1}, {2, 4},
			{5, 9}, {8, 6}, {7, 1}, {4, 3}, {5, 2}, {6, 9}, {8, 7}, {4, 1}, {5, 3}, {6, 2},
			{9, 7}, {1, 8}, {4, 5}, {3, 6}, {2, 7}, {9, 8},
		}
	case 10:
		return [][2]int{
			{1, 4}, {6, 9}, {2, 5}, {7, 10}, {3, 1}, {8, 6}, {4, 5}, {9, 10}, {2, 3}, {7, 8},
			{5, 1}, {10, 6}, {4, 2}, {9, 7}, {5, 3}, {10, 8}, {1, 2}, {6, 7}, {3, 4}, {8, 9},
			{5, 10}, {1, 6}, {2, 7}, {3, 8}, {4, 9}, {6, 5}, {10, 2}, {8, 1}, {7, 4}, {9, 3},
			{2, 6}, {5, 8}, {4, 10}, {1, 9}, {3, 7}, {8, 2}, {6, 4}, {9, 5}, {10, 3}, {7, 1},
			{4, 8}, {2, 9}, {3, 6}, {5, 7}, {1, 10},
		}
	default:
		return nil
	}
}
